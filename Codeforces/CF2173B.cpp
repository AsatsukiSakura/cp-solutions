void solve(){
	int n;
	cin>>n;
	vector<int>a(n+1),b(n+1);
	for(int i=1;i<=n;i++){
		cin>>a[i];
	}
	for(int i=1;i<=n;i++){
		cin>>b[i];
	}
	ll mx=0,mn=0;
	for(int i=1;i<=n;i++){
		ll tmp=max(1ll*b[i]-mn,mx-1ll*a[i]);
		mn=min(1ll*b[i]-mx,mn-1ll*a[i]);
		mx=tmp;
	}
	cout<<mx<<endl;
	
}
int main(){
	ios::sync_with_stdio(false);
	cin.tie(nullptr);
	int t;cin>>t;
	while(t--)solve();
	return 0;
}
